import { z } from "zod";
export const MAX_PHOTOS = 8;
export const MAX_PHOTO_BYTES = 15 * 1024 * 1024;
export const MAX_PHOTO_PIXELS = 40_000_000;
export const PHOTO_RETENTION_MS = 7 * 24 * 60 * 60 * 1000;
export const PHOTO_UPLOAD_EXPIRES_SECONDS = 300;
export const PHOTO_UPLOAD_TIMEOUT_MS = 15 * 60 * 1000;
const id = z.string().regex(/^[A-Za-z0-9_-]{1,80}$/);
const alt = z.string().trim().min(1, "Descreva a foto.").max(180, "Use até 180 caracteres.").refine(value => !value.includes("\0"), "Descrição inválida.");
export const fotoInicioSchema = z.strictObject({ alt, tamanho: z.number().int().positive().max(MAX_PHOTO_BYTES), mimeTipo: z.enum(["image/jpeg", "image/png", "image/webp", "image/heic", "image/heif"]), substituirId: id.optional() });
export const fotoVersaoSchema = z.strictObject({ versao: z.number().int().positive() });
export const fotoAltSchema = fotoVersaoSchema.extend({ alt });
export const fotoOrdemSchema = fotoVersaoSchema.extend({ ids: z.array(id).max(MAX_PHOTOS).refine(ids => new Set(ids).size === ids.length, "Não repita fotos.") });
export const fotoConfirmarSchema = z.strictObject({});
export type FotoInicio = z.infer<typeof fotoInicioSchema>;
export type FotoDTO = { id: string; alt: string; ordem: number; status: "AGUARDANDO_UPLOAD" | "PROCESSANDO" | "PRONTA" | "ERRO"; temFoto: boolean; hash: string | null; blurDataUrl: string | null; larguraOrig: number | null; alturaOrig: number | null; mensagem: string | null; removidaEm: string | null; restauravelAte: string | null };
export type GaleriaDTO = { versao: number; imagens: FotoDTO[]; removidas: FotoDTO[] };
export type FotoUploadDTO = { id: string; url: string; expiresEm: string };
export const PHOTO_VARIANTS = ["thumb.webp", "thumb.avif", "card.webp", "card.avif", "produto.webp", "produto.avif", "zoom.webp", "zoom.avif", "social.jpg"] as const;
export type PhotoVariant = typeof PHOTO_VARIANTS[number];
